export function isSystemObject(item) {
  const name = String(item.name || "").trim().toLowerCase();
  if (item.mimeType === FOLDER_MIME) return SYSTEM_FOLDER_PATTERN.test(name);
  return SYSTEM_FILE_PATTERN.test(name);
}

function isMemoryFile(item) {
  return Object.values(MEMORY_FILE_NAMES).includes(item.name);
}

export function classifyChange(previous, item) {
  if (!previous) return ["NEW"];
  const types = [];
  const contentChanged =
    String(previous.modified_time || "") !== String(item.modifiedTime || "") ||
    String(previous.size || "") !== String(item.size ?? "") ||
    (item.md5Checksum && String(previous.md5 || "") !== String(item.md5Checksum));
  if (item.mimeType !== FOLDER_MIME && contentChanged) types.push("MODIFIED");
  if (previous.name !== item.name) types.push("RENAMED");
  if (String(previous.parent_id || "") !== String(item.parents?.[0] || "")) types.push("MOVED");
  return types.length ? types : ["UNCHANGED"];
}

function emptyRegisterRow() {
  return Object.fromEntries(REGISTER_COLUMNS.map(column => [column, ""]));
}

export async function runMappingPass(drive, {
  memoryFolderId,
  rootFolderId,
  listing = null,
  maxReads = 150,
  maxItems = 20000,
  readChars = 30000,
  now = new Date(),
  org = ""
}) {
  const nowIso = now.toISOString();
  const memory = await openMemory(drive, { memoryFolderId, org });
  const memoryIds = new Set([memory.map.fileId, memory.register.fileId].filter(Boolean));
  const current = listing || await walkDrive(drive, rootFolderId, { maxItems, excludeIds: memoryIds });

  const previousById = new Map(memory.register.rows.map(row => [row.file_id, row]));
  const seen = new Set();
  const counts = Object.fromEntries([...CHANGE_TYPES, "MISSING_PENDING_CHECK", "MOVED_OUT_OF_SCOPE", "TRASHED", "REAPPEARED"].map(t => [t, 0]));
  const toRead = [];

  for (const item of current.items) {
    if (memoryIds.has(item.id)) continue;
    seen.add(item.id);
    const previous = previousById.get(item.id);
    const types = classifyChange(previous, item);
    const row = previous || emptyRegisterRow();
    const wasAbsent = previous && previous.status && previous.status !== "PRESENT";

    Object.assign(row, {
      file_id: item.id,
      parent_id: item.parents?.[0] || "",
      name: item.name,
      path: item.path || row.path || "",
      mime_type: item.mimeType,
      size: String(item.size ?? ""),
      modified_time: item.modifiedTime || "",
      created_time: item.createdTime || row.created_time || "",
      md5: item.md5Checksum || row.md5 || "",
      web_url: item.webViewLink || row.web_url || "",
      is_folder: item.mimeType === FOLDER_MIME ? "true" : "false",
      first_seen_at: row.first_seen_at || nowIso,
      last_seen_at: nowIso,
      status: "PRESENT",
      change_type: types.join("+"),
      missing_since: "",
      missing_checks: "0"
    });
    if (!previous) memory.register.rows.push(row);
    for (const type of types) counts[type] += 1;
    if (wasAbsent) counts.REAPPEARED += 1;

    const changed = !types.includes("UNCHANGED");
    if (isMemoryFile(item)) {
      row.semantic_role = "OFFICE_MANAGER_MEMORY";
      row.understanding_status = "METADATA_ONLY";
      row.read_status = "SKIPPED_SYSTEM";
      continue;
    }
    if (isSystemObject(item)) {
      row.understanding_status = "METADATA_ONLY";
      row.read_status = "SKIPPED_SYSTEM";
      continue;
    }
    if (row.is_folder === "true") {
      // Folders are understood by the AI from their name, place and children.
      if (changed || !row.understanding_status) row.understanding_status = "NEEDS_UNDERSTANDING";
      continue;
    }
    if (changed || row.understanding_status === "PENDING_READ" || !row.understanding_status) {
      row.understanding_status = "PENDING_READ";
      row._renamedOrMoved = types.includes("RENAMED") || types.includes("MOVED") || types.includes("NEW");
      toRead.push(row);
    }
  }

  // Absent objects: never concluded deleted on first absence.
  if (current.complete) {
    for (const row of memory.register.rows) {
      if (seen.has(row.file_id) || memoryIds.has(row.file_id)) continue;
      if (["DELETED_OR_MISSING", "TRASHED"].includes(row.status)) continue;
      const meta = await drive.getMeta(row.file_id).catch(() => null);
      if (meta && meta.trashed) {
        row.status = "TRASHED";
        row.change_type = "TRASHED";
        counts.TRASHED += 1;
      } else if (meta) {
        row.status = "MOVED_OUT_OF_SCOPE";
        row.parent_id = meta.parents?.[0] || row.parent_id;
        row.name = meta.name || row.name;
        row.change_type = "MOVED";
        counts.MOVED_OUT_OF_SCOPE += 1;
      } else {
        const checks = Number(row.missing_checks || 0) + 1;
        row.missing_checks = String(checks);
        row.missing_since = row.missing_since || nowIso;
        if (checks >= MISSING_CONFIRMATION_PASSES) {
          row.status = "DELETED_OR_MISSING";
          row.change_type = "DELETED_OR_MISSING";
          counts.DELETED_OR_MISSING += 1;
        } else {
          row.status = "MISSING_PENDING_CHECK";
          row.change_type = "MISSING_PENDING_CHECK";
          counts.MISSING_PENDING_CHECK += 1;
        }
      }
      row.last_action = `PRESENCE_CHECK_${row.status}`;
      row.last_action_at = nowIso;
    }
  }

  // Open + read changed business files (bounded); UNCHANGED files are never re-read.
  let readsDone = 0;
  for (const row of toRead) {
    const renamedOrMoved = row._renamedOrMoved;
    delete row._renamedOrMoved;
    if (!READABLE_MIMES.has(row.mime_type) && !String(row.mime_type).startsWith("text/")) {
      row.read_status = "EXTRACTOR_REQUIRED";
      row.understanding_status = "EXTRACTOR_REQUIRED";
      continue;
    }
    if (readsDone >= maxReads) continue; // stays PENDING_READ for the next pass
    readsDone += 1;
    const read = await drive.readText(row.file_id, { maxChars: readChars })
      .catch(error => ({ supported: false, reason: error.message }));
    row.last_inspected_at = nowIso;
    if (!read.supported) {
      row.read_status = "EXTRACTOR_REQUIRED";
      row.understanding_status = "EXTRACTOR_REQUIRED";
      continue;
    }
    const fingerprint = contentFingerprint(read.file || { id: row.file_id, modifiedTime: row.modified_time }, read.text);
    const sameContent = row.content_fingerprint && row.content_fingerprint === fingerprint;
    row.content_fingerprint = fingerprint;
    row.read_status = "READ";
    row.understanding_status =
      sameContent && !renamedOrMoved && row.semantic_role ? "UNDERSTOOD" : "NEEDS_UNDERSTANDING";
    row.last_action = "READ";
    row.last_action_at = nowIso;
  }
  for (const row of toRead) delete row._renamedOrMoved;

  // MAP follows roles, not paths: refresh names/paths of mapped targets.
  for (const mapRow of memory.map.sheets.MAP) {
    const target = registerRow(memory, mapRow.target_file_id);
    if (!target) continue;
    mapRow.target_name = target.name;
    mapRow.target_path = target.path;
    mapRow.last_verified_at = nowIso;
    if (target.status !== "PRESENT" && mapRow.canonical_status !== "REJECTED") {
      mapRow.notes = `target ${target.status} at ${nowIso}`;
    }
  }

  const previousState = getState(memory, "mapping_state") || MAPPING_STATES.FIRST_MAPPING;
  if (previousState === MAPPING_STATES.FIRST_MAPPING && current.complete) {
    setState(memory, "mapping_state", MAPPING_STATES.MAPPING_PENDING_REVIEW, nowIso);
  }
  const scanCount = Number(getState(memory, "scan_count") || 0) + 1;
  setState(memory, "scan_count", scanCount, nowIso);
  setState(memory, "last_scan_at", nowIso, nowIso);
  setState(memory, "last_scan_complete", current.complete ? "true" : "false", nowIso);
  setState(memory, "last_listing_source", current.source, nowIso);
  setState(memory, "last_pass_summary", JSON.stringify(counts), nowIso);

  const saved = await saveMemory(drive, memory);

  const pendingReads = memory.register.rows.filter(r => r.understanding_status === "PENDING_READ").length;
  const needsUnderstanding = memory.register.rows.filter(r => r.understanding_status === "NEEDS_UNDERSTANDING").length;
  return {
    memory,
    summary: {
      pass_mode: scanCount === 1 ? "FIRST_MAPPING" : "DIFFERENTIAL",
      mapping_state: getState(memory, "mapping_state"),
      listing_source: current.source,
      listing_complete: current.complete,
      objects_seen: seen.size,
      counts,
      reads_done: readsDone,
      pending_reads: pendingReads,
      needs_understanding: needsUnderstanding,
      business_actions_performed: 0,
      ...saved
    }
  };
}

