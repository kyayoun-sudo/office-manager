export function recordUnderstanding(memory, items, { now }) {
  const results = [];
  for (const item of items) {
    const row = registerRow(memory, item.file_id);
    if (!row) {
      results.push({ file_id: item.file_id, status: "NOT_IN_REGISTER" });
      continue;
    }
    if (!SEMANTIC_ROLES[item.semantic_role]) {
      results.push({ file_id: item.file_id, status: "UNKNOWN_SEMANTIC_ROLE" });
      continue;
    }
    if (row.is_folder !== "true") {
      if (row.read_status !== "READ") {
        results.push({ file_id: item.file_id, status: "NOT_READ_YET" });
        continue;
      }
      if (item.content_fingerprint !== row.content_fingerprint) {
        results.push({ file_id: item.file_id, status: "STALE_FINGERPRINT" });
        continue;
      }
    }
    Object.assign(row, {
      semantic_role: item.semantic_role,
      classification: String(item.classification || "").slice(0, 120),
      client: String(item.client || "").slice(0, 120),
      mission: String(item.mission || "").slice(0, 120),
      understanding_status: "UNDERSTOOD",
      understanding_confidence: String(item.confidence ?? ""),
      understanding_rationale: String(item.rationale || "").slice(0, 800),
      last_action: "UNDERSTOOD_BY_AI",
      last_action_at: now
    });
    results.push({ file_id: item.file_id, status: "RECORDED" });
  }
  return results;
}

// ---------------------------------------------------------------------------
// Owner report: how the AI understood the organisation + what needs validation
// ---------------------------------------------------------------------------

export function buildMappingReport(memory, secret) {
  const rows = memory.register.rows;
  const byRole = {};
  for (const row of rows) {
    if (row.status !== "PRESENT") continue;
    const role = row.semantic_role || "UNKNOWN";
    byRole[role] = (byRole[role] || 0) + 1;
  }
  const roles = SEMANTIC_ROLE_KEYS.map(role => ({ role, resolution: resolveSemanticRole(memory, role, secret) }));
  const questions = [];
  for (const { role, resolution } of roles) {
    if (SEMANTIC_ROLES[role].cardinality !== "SINGLE" || role === "OFFICE_MANAGER_MEMORY") continue;
    if (resolution.status === "REVIEW_REQUIRED") {
      questions.push({ semantic_role: role, question: "REVIEW_REQUIRED", detail: resolution });
    } else if (resolution.status === "NO_OWNER_APPROVAL" && resolution.hypotheses.length) {
      questions.push({
        semantic_role: role,
        question: resolution.hypotheses.length > 1 ? "WHICH_ONE_IS_CANONICAL" : "CONFIRM_CANONICAL",
        candidates: resolution.hypotheses
      });
    }
  }
  return {
    mapping_state: mappingState(memory, secret),
    scan_count: Number(getState(memory, "scan_count") || 0),
    last_scan_at: getState(memory, "last_scan_at"),
    last_scan_complete: getState(memory, "last_scan_complete") === "true",
    objects: {
      total: rows.length,
      present: rows.filter(r => r.status === "PRESENT").length,
      folders: rows.filter(r => r.is_folder === "true" && r.status === "PRESENT").length,
      pending_read: rows.filter(r => r.understanding_status === "PENDING_READ").length,
      needs_understanding: rows.filter(r => r.understanding_status === "NEEDS_UNDERSTANDING").length,
      understood: rows.filter(r => r.understanding_status === "UNDERSTOOD").length,
      extractor_required: rows.filter(r => r.understanding_status === "EXTRACTOR_REQUIRED").length,
      missing_pending_check: rows.filter(r => r.status === "MISSING_PENDING_CHECK").length
    },
    objects_by_role: byRole,
    roles: roles.map(({ role, resolution }) => ({ role, status: resolution.status, targets: resolution.targets || [], hypotheses: resolution.hypotheses || [] })),
    owner_questions: questions
  };
}
