// Orpailleur memory — OFFICE_MANAGER_MAP.xlsx + OFFICE_MANAGER_REGISTER.xlsx
//
//   MAP the authorised Drive first -> EXPLAIN -> owner VALIDATES ambiguities
//   -> REMEMBER (signed RULES) -> only then ACT.
//
// - MAP (business understanding) holds sheets MAP, RULES, ROLES, STATE.
//   Memory is about ROLES ("folder X is currently the
//   WORKING_PAPER_TEMPLATE_LIBRARY"), never about frozen paths: rows are keyed
//   by file_id and the path is refreshed on every pass.
// - RULES are the owner's memory. A rule is valid only if it carries an HMAC
//   signature made with OWNER_APPROVAL_SECRET, which only the owner endpoint
//   (api/owner.js) holds. The agent cannot create or forge one; a sentence
//   generated by the AI is never an approval.
// - REGISTER (technical memory) has one row per Drive object keyed by file_id,
//   used for differential passes: UNCHANGED / NEW / MODIFIED / RENAMED / MOVED
//   / DELETED_OR_MISSING (after verification, never on first absence).
// - The pass is READ-ONLY on business files: it only reads the Drive and
//   creates/updates the two memory files in place (same file_id every run).
// - Understanding is done by the AI (record_file_understanding). This module
//   never decides a file's business meaning; MAP never replaces reasoning.
//
// Drive adapter used here (in addition to lib/mission-engine.js's):
//   findFilesByExactName(name, parentId) -> [meta]
//   downloadBuffer(id) -> Buffer
//   createBinary({ name, parentId, buffer, mimeType }) -> meta
//   updateBinary(id, { buffer, mimeType }) -> meta

