function newMapRow(memory, { semanticRole, targetFileId, proposedBy, now, confidence, rationale }) {
  const target = registerRow(memory, targetFileId);
  return {
    map_id: `MAP-${sha256([semanticRole, targetFileId].join("|")).slice(0, 12)}`,
    org: getState(memory, "org"),
    semantic_role: semanticRole,
    target_file_id: targetFileId,
    target_kind: target?.is_folder === "true" ? "FOLDER" : "FILE",
    target_name: target?.name || "",
    target_path: target?.path || "",
    canonical_status: "AI_HYPOTHESIS",
    confidence: String(confidence ?? ""),
    rationale: String(rationale || "").slice(0, 1000),
    owner_approval_status: "PENDING",
    rule_id: "",
    proposed_by: proposedBy,
    proposed_at: now,
    last_verified_at: now,
    notes: ""
  };
}

// The AI may PROPOSE a role; it can never approve one.
export function proposeRole(memory, { semanticRole, targetFileId, confidence, rationale, now }) {
  if (!SEMANTIC_ROLES[semanticRole]) return { status: "UNKNOWN_SEMANTIC_ROLE" };
  const target = registerRow(memory, targetFileId);
  if (!target || target.status !== "PRESENT") return { status: "TARGET_NOT_IN_REGISTER" };
  const existing = memory.map.sheets.MAP.find(r => r.semantic_role === semanticRole && r.target_file_id === targetFileId);
  if (existing) {
    if (existing.canonical_status === "AI_HYPOTHESIS") {
      existing.confidence = String(confidence ?? existing.confidence);
      existing.rationale = String(rationale || existing.rationale).slice(0, 1000);
      existing.last_verified_at = now;
    }
    return { status: "ALREADY_MAPPED", map_row: existing };
  }
  const row = newMapRow(memory, { semanticRole, targetFileId, proposedBy: "AI", now, confidence, rationale });
  memory.map.sheets.MAP.push(row);
  return { status: "PROPOSED", map_row: row };
}

// resolve_semantic_role:
//   OWNER_APPROVED   -> use it (library_basis OWNER_APPROVED_MAP)
//   REVIEW_REQUIRED  -> concurrent owner rules for a SINGLE role, or approved target missing
//   NO_OWNER_APPROVAL-> no owner rule: normal discovery (hypotheses returned as hints)
export function resolveSemanticRole(memory, semanticRole, secret) {
  if (!SEMANTIC_ROLES[semanticRole]) return { status: "UNKNOWN_SEMANTIC_ROLE", semantic_role: semanticRole };
  const predicate = rule => rule.rule_type === "CANONICAL_ROLE_ASSIGNMENT" && rule.semantic_role === semanticRole;
  const valid = activeValidRules(memory, secret, predicate);
  const ignored = unverifiedOwnerClaims(memory, secret, predicate).map(rule => rule.rule_id);
  const hypotheses = memory.map.sheets.MAP
    .filter(row => row.semantic_role === semanticRole && row.canonical_status === "AI_HYPOTHESIS")
    .map(row => ({ target_file_id: row.target_file_id, target_name: row.target_name, target_path: row.target_path, confidence: row.confidence }));

  if (!valid.length) {
    return {
      status: "NO_OWNER_APPROVAL",
      semantic_role: semanticRole,
      hypotheses,
      ambiguous: SEMANTIC_ROLES[semanticRole].cardinality === "SINGLE" && hypotheses.length > 1,
      unverified_rules_ignored: ignored
    };
  }
  if (SEMANTIC_ROLES[semanticRole].cardinality === "SINGLE" && valid.length > 1) {
    return { status: "REVIEW_REQUIRED", reason: "CONCURRENT_OWNER_RULES", semantic_role: semanticRole, rule_ids: valid.map(r => r.rule_id) };
  }

  const targets = [];
  for (const rule of valid) {
    const row = registerRow(memory, rule.target_file_id);
    if (!row || row.status !== "PRESENT") {
      return { status: "REVIEW_REQUIRED", reason: "APPROVED_TARGET_MISSING", semantic_role: semanticRole, rule_id: rule.rule_id, target_file_id: rule.target_file_id, presence: row?.status || "UNKNOWN" };
    }
    targets.push({ target_file_id: row.file_id, name: row.name, path: row.path, rule_id: rule.rule_id, approved_by: rule.approved_by, approved_at: rule.approved_at });
  }
  return {
    status: "OWNER_APPROVED",
    basis: "OWNER_APPROVED_MAP",
    semantic_role: semanticRole,
    target_file_id: targets.length === 1 ? targets[0].target_file_id : null,
    targets,
    unverified_rules_ignored: ignored
  };
}

// ---------------------------------------------------------------------------
// Listing (Drive walk, or the existing orpailleur_inventory scanner)
// ---------------------------------------------------------------------------

export async function walkDrive(drive, rootFolderId, { maxItems = 20000, excludeIds = new Set() } = {}) {
  const items = [];
  const queue = [{ id: rootFolderId, path: "" }];
  let complete = true;
  while (queue.length) {
    const { id, path } = queue.shift();
    const children = await drive.listChildren(id);
    for (const child of children) {
      if (excludeIds.has(child.id)) continue;
      if (items.length >= maxItems) {
        complete = false;
        break;
      }
      const childPath = `${path}/${child.name}`;
      items.push({ ...child, parents: child.parents?.length ? child.parents : [id], path: childPath });
      if (child.mimeType === FOLDER_MIME) queue.push({ id: child.id, path: childPath });
    }
    if (!complete) break;
  }
  return { source: "DRIVE_WALK", items, complete };
}

// Rows of orpailleur_inventory seen by the latest scan run (existing durable
// scanner, reused as-is). complete=true only for a COMPLETE run.
export function listingFromInventory(rows, { runId, runStatus }) {
  const items = (rows || [])
    .filter(row => !runId || row.last_scan_id === runId)
    .map(row => ({
      id: row.file_id,
      name: row.name,
      mimeType: row.mime_type,
      parents: row.parent_id ? [row.parent_id] : [],
      modifiedTime: row.modified_at || "",
      size: row.size_bytes ?? "",
      webViewLink: row.web_url || "",
      version: row.drive_version || "",
      path: `${String(row.folder_path || "/").replace(/\/$/, "")}/${row.name}`
    }));
  return { source: "ORPAILLEUR_INVENTORY", items, complete: runStatus === "COMPLETE", run_id: runId || null };
}

