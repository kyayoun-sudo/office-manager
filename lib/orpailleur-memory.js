function rolesCatalog() {
  return SEMANTIC_ROLE_KEYS.map(role => ({
    semantic_role: role,
    cardinality: SEMANTIC_ROLES[role].cardinality,
    description: SEMANTIC_ROLES[role].description,
    requires_owner_approval: SEMANTIC_ROLES[role].cardinality === "SINGLE" ? "true" : "false",
    used_by: SEMANTIC_ROLES[role].used_by || ""
  }));
}

export async function openMemory(drive, { memoryFolderId, org = "" }) {
  const memory = {
    memoryFolderId,
    exists: false,
    map: { fileId: null, modifiedTime: null, sheets: { MAP: [], RULES: [], ROLES: rolesCatalog(), STATE: [] } },
    register: { fileId: null, modifiedTime: null, rows: [] }
  };

  for (const kind of ["map", "register"]) {
    const found = await drive.findFilesByExactName(MEMORY_FILE_NAMES[kind], memoryFolderId);
    if (found.length > 1) {
      // Never create a third file, never pick one arbitrarily.
      throw new Error(`MEMORY_FILE_DUPLICATE: ${found.length} files named ${MEMORY_FILE_NAMES[kind]}`);
    }
    if (!found.length) continue;
    const meta = found[0];
    const buffer = await drive.downloadBuffer(meta.id);
    if (kind === "map") {
      const sheets = await parseWorkbookBuffer(buffer, MAP_SCHEMA);
      memory.map = {
        fileId: meta.id,
        modifiedTime: meta.modifiedTime,
        sheets: { ...sheets, ROLES: sheets.ROLES.length ? sheets.ROLES : rolesCatalog() }
      };
    } else {
      const sheets = await parseWorkbookBuffer(buffer, REGISTER_SCHEMA);
      memory.register = { fileId: meta.id, modifiedTime: meta.modifiedTime, rows: sheets.REGISTER };
    }
  }

  memory.exists = Boolean(memory.map.fileId);
  if (!getState(memory, "mapping_state")) {
    setState(memory, "mapping_state", MAPPING_STATES.FIRST_MAPPING, new Date().toISOString());
  }
  if (org && !getState(memory, "org")) setState(memory, "org", org, new Date().toISOString());
  return memory;
}

export async function saveMemory(drive, memory) {
  const files = {
    map: await buildWorkbookBuffer({
      MAP: { columns: MAP_COLUMNS, rows: memory.map.sheets.MAP },
      RULES: { columns: RULES_COLUMNS, rows: memory.map.sheets.RULES },
      ROLES: { columns: ROLES_COLUMNS, rows: memory.map.sheets.ROLES },
      STATE: { columns: STATE_COLUMNS, rows: memory.map.sheets.STATE }
    }),
    register: await buildWorkbookBuffer({
      REGISTER: { columns: REGISTER_COLUMNS, rows: memory.register.rows }
    })
  };

  // Optimistic concurrency: if a memory file changed since it was loaded
  // (e.g. the owner edited it), abort instead of overwriting.
  for (const kind of ["map", "register"]) {
    const target = memory[kind];
    if (!target.fileId) continue;
    const meta = await drive.getMeta(target.fileId);
    if (meta.modifiedTime !== target.modifiedTime) {
      throw new Error(`MEMORY_CONFLICT: ${MEMORY_FILE_NAMES[kind]} changed since it was loaded`);
    }
  }

  for (const kind of ["map", "register"]) {
    const target = memory[kind];
    const result = target.fileId
      ? await drive.updateBinary(target.fileId, {
          buffer: files[kind],
          mimeType: XLSX_MIME,
          // Re-checked by the writer itself (bridge or direct): on mismatch
          // MEMORY_CONFLICT and nothing is written.
          expectedModifiedTime: target.modifiedTime
        })
      : await drive.createBinary({
          name: MEMORY_FILE_NAMES[kind],
          parentId: memory.memoryFolderId,
          buffer: files[kind],
          mimeType: XLSX_MIME
        });
    target.fileId = result.id;
    target.modifiedTime = result.modifiedTime || target.modifiedTime;
  }
  memory.exists = true;
  return { map_file_id: memory.map.fileId, register_file_id: memory.register.fileId };
}

export function getState(memory, key) {
  return memory.map.sheets.STATE.find(row => row.key === key)?.value || "";
}

export function setState(memory, key, value, now) {
  const row = memory.map.sheets.STATE.find(item => item.key === key);
  if (row) {
    row.value = String(value);
    row.updated_at = now;
  } else {
    memory.map.sheets.STATE.push({ key, value: String(value), updated_at: now });
  }
}

// ---------------------------------------------------------------------------
// Owner rules: signed, verifiable, never produced by the agent
// ---------------------------------------------------------------------------

function canonicalRule(rule) {
  return [
    rule.rule_id, rule.rule_type, rule.semantic_role, rule.target_file_id,
    rule.approval_source, rule.approved_by, rule.approved_at, String(rule.active)
  ].join("|");
}

export function signRule(rule, secret) {
  if (!secret) throw new Error("OWNER_APPROVAL_SECRET_MISSING");
  return createHmac("sha256", secret).update(canonicalRule(rule)).digest("hex");
}

export function verifyRule(rule, secret) {
  if (!secret || rule.approval_source !== "OWNER" || !rule.signature) return false;
  const expected = Buffer.from(signRule(rule, secret), "hex");
  const given = Buffer.from(String(rule.signature), "hex");
  return expected.length === given.length && timingSafeEqual(expected, given);
}

function activeValidRules(memory, secret, predicate) {
  return memory.map.sheets.RULES.filter(rule =>
    String(rule.active) === "true" && predicate(rule) && verifyRule(rule, secret)
  );
}

function unverifiedOwnerClaims(memory, secret, predicate) {
  return memory.map.sheets.RULES.filter(rule =>
    String(rule.active) === "true" && predicate(rule) && !verifyRule(rule, secret)
  );
}

// MAPPING_REVIEWED exists ONLY through an active owner-signed rule. A STATE
// cell edited by hand (or by anything else) claiming it is not trusted.
export function mappingState(memory, secret) {
  const reviewed = activeValidRules(memory, secret, rule => rule.rule_type === "MAPPING_REVIEWED");
  if (reviewed.length) return MAPPING_STATES.MAPPING_REVIEWED;
  const declared = getState(memory, "mapping_state") || MAPPING_STATES.FIRST_MAPPING;
  return declared === MAPPING_STATES.MAPPING_REVIEWED ? MAPPING_STATES.MAPPING_PENDING_REVIEW : declared;
}

// Business documentary actions start only once the owner reviewed the mapping.
export function documentaryActionsAllowed(memory, secret) {
  if (!memory?.exists) return { allowed: false, state: "NO_MAP", reason: "MAPPING_REQUIRED" };
  const state = mappingState(memory, secret);
  return state === MAPPING_STATES.MAPPING_REVIEWED
    ? { allowed: true, state }
    : { allowed: false, state, reason: "MAPPING_NOT_REVIEWED" };
}

function registerRow(memory, fileId) {
  return memory.register.rows.find(row => row.file_id === fileId) || null;
}

function ruleId(parts) {
  return `RULE-${sha256(parts.join("|")).slice(0, 12)}`;
}

function resign(rule, secret) {
  rule.signature = signRule(rule, secret);
}

// Owner actions — only called by api/owner.js (owner credential), never by a tool.
export function ownerApproveRole(memory, { semanticRole, targetFileId, approvedBy, secret, now, notes = "" }) {
  if (!secret) throw new Error("OWNER_APPROVAL_SECRET_MISSING");
  if (!SEMANTIC_ROLES[semanticRole]) throw new Error("UNKNOWN_SEMANTIC_ROLE");
  if (!String(approvedBy || "").trim()) throw new Error("APPROVER_REQUIRED");
  const target = registerRow(memory, targetFileId);
  if (!target || target.status !== "PRESENT") throw new Error("TARGET_NOT_IN_REGISTER");

  if (SEMANTIC_ROLES[semanticRole].cardinality === "SINGLE") {
    for (const rule of activeValidRules(memory, secret, r =>
      r.rule_type === "CANONICAL_ROLE_ASSIGNMENT" && r.semantic_role === semanticRole)) {
      rule.active = "false";
      rule.notes = `${rule.notes || ""} superseded ${now}`.trim();
      resign(rule, secret);
    }
  }

  const rule = {
    rule_id: ruleId([semanticRole, targetFileId, now]),
    rule_type: "CANONICAL_ROLE_ASSIGNMENT",
    semantic_role: semanticRole,
    target_file_id: targetFileId,
    target_name_at_approval: target.name,
    approval_source: "OWNER",
    approved_by: approvedBy,
    approved_at: now,
    active: "true",
    signature: "",
    notes
  };
  resign(rule, secret);
  memory.map.sheets.RULES.push(rule);

  let mapRow = memory.map.sheets.MAP.find(r => r.semantic_role === semanticRole && r.target_file_id === targetFileId);
  if (!mapRow) {
    mapRow = newMapRow(memory, { semanticRole, targetFileId, proposedBy: "OWNER", now, confidence: "1", rationale: "Owner assignment" });
    memory.map.sheets.MAP.push(mapRow);
  }
  mapRow.canonical_status = "OWNER_APPROVED";
  mapRow.owner_approval_status = "APPROVED";
  mapRow.rule_id = rule.rule_id;
  mapRow.last_verified_at = now;
  if (SEMANTIC_ROLES[semanticRole].cardinality === "SINGLE") {
    for (const other of memory.map.sheets.MAP) {
      if (other !== mapRow && other.semantic_role === semanticRole && other.canonical_status !== "REJECTED") {
        other.canonical_status = "SUPERSEDED";
      }
    }
  }
  return rule;
}

export function ownerRejectRole(memory, { semanticRole, targetFileId, approvedBy, secret, now, notes = "" }) {
  if (!secret) throw new Error("OWNER_APPROVAL_SECRET_MISSING");
  const rule = {
    rule_id: ruleId(["reject", semanticRole, targetFileId, now]),
    rule_type: "ROLE_REJECTION",
    semantic_role: semanticRole,
    target_file_id: targetFileId,
    target_name_at_approval: registerRow(memory, targetFileId)?.name || "",
    approval_source: "OWNER",
    approved_by: approvedBy,
    approved_at: now,
    active: "true",
    signature: "",
    notes
  };
  resign(rule, secret);
  memory.map.sheets.RULES.push(rule);
  for (const row of memory.map.sheets.MAP) {
    if (row.semantic_role === semanticRole && row.target_file_id === targetFileId) {
      row.canonical_status = "REJECTED";
      row.owner_approval_status = "REJECTED";
      row.rule_id = rule.rule_id;
    }
  }
  return rule;
}

export function ownerDeactivateRule(memory, { ruleIdToDeactivate, secret, now }) {
  const rule = memory.map.sheets.RULES.find(r => r.rule_id === ruleIdToDeactivate);
  if (!rule || !verifyRule(rule, secret)) throw new Error("RULE_NOT_FOUND_OR_UNVERIFIED");
  rule.active = "false";
  rule.notes = `${rule.notes || ""} deactivated ${now}`.trim();
  resign(rule, secret);
  return rule;
}

export function ownerMarkMappingReviewed(memory, { approvedBy, secret, now }) {
  if (!secret) throw new Error("OWNER_APPROVAL_SECRET_MISSING");
  const state = mappingState(memory, secret);
  if (state === MAPPING_STATES.FIRST_MAPPING) throw new Error("FIRST_MAPPING_NOT_COMPLETE");
  const rule = {
    rule_id: ruleId(["mapping-reviewed", now]),
    rule_type: "MAPPING_REVIEWED",
    semantic_role: "",
    target_file_id: "",
    target_name_at_approval: "",
    approval_source: "OWNER",
    approved_by: approvedBy,
    approved_at: now,
    active: "true",
    signature: "",
    notes: ""
  };
  resign(rule, secret);
  memory.map.sheets.RULES.push(rule);
  setState(memory, "mapping_state", MAPPING_STATES.MAPPING_REVIEWED, now);
  return rule;
}

