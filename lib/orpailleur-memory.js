function cellText(value) {
  if (value === null || value === undefined) return "";
  if (typeof value === "object") {
    if (value.richText) return value.richText.map(part => part.text).join("");
    if (value.text !== undefined) return String(value.text);
    if (value.result !== undefined) return String(value.result);
    if (value instanceof Date) return value.toISOString();
  }
  return String(value);
}

export async function buildWorkbookBuffer(sheets) {
  const workbook = new ExcelJS.Workbook();
  workbook.creator = "Office Manager AI";
  for (const [name, { columns, rows }] of Object.entries(sheets)) {
    const sheet = workbook.addWorksheet(name);
    sheet.addRow(columns);
    sheet.getRow(1).font = { bold: true };
    for (const row of rows) sheet.addRow(columns.map(column => String(row[column] ?? "")));
  }
  return Buffer.from(await workbook.xlsx.writeBuffer());
}

export async function parseWorkbookBuffer(buffer, schema) {
  const workbook = new ExcelJS.Workbook();
  await workbook.xlsx.load(buffer);
  const out = {};
  for (const [name, columns] of Object.entries(schema)) {
    const sheet = workbook.getWorksheet(name);
    out[name] = [];
    if (!sheet) continue;
    const header = [];
    sheet.getRow(1).eachCell({ includeEmpty: true }, (cell, col) => {
      header[col - 1] = cellText(cell.value).trim();
    });
    sheet.eachRow({ includeEmpty: false }, (row, rowNumber) => {
      if (rowNumber === 1) return;
      const obj = {};
      for (const column of columns) {
        const index = header.indexOf(column);
        obj[column] = index >= 0 ? cellText(row.getCell(index + 1).value) : "";
      }
      if (Object.values(obj).some(v => String(v).trim())) out[name].push(obj);
    });
  }
  return out;
}

const MAP_SCHEMA = { MAP: MAP_COLUMNS, RULES: RULES_COLUMNS, ROLES: ROLES_COLUMNS, STATE: STATE_COLUMNS };
const REGISTER_SCHEMA = { REGISTER: REGISTER_COLUMNS };

